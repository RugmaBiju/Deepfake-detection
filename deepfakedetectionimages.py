import torch
import timm
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import torch.nn as nn
from torch.utils.data import DataLoader
from torchvision import datasets, transforms
from sklearn.metrics import confusion_matrix, classification_report

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print("Training on:", device)

# 1. Native 1:1 crops preserve Stable Diffusion VAE decoder fingerprints
train_tf = transforms.Compose([
    transforms.RandomCrop(224, pad_if_needed=True, padding_mode="reflect"),
    transforms.RandomHorizontalFlip(),
    transforms.RandomVerticalFlip(),
    transforms.ToTensor(),
    transforms.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225])
])

val_tf = transforms.Compose([
    transforms.CenterCrop(224),
    transforms.ToTensor(),
    transforms.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225])
])

train_ds = datasets.ImageFolder(TRAIN_DIR, transform=train_tf)
val_ds = datasets.ImageFolder(VAL_DIR, transform=val_tf)
print("Class Mapping:", train_ds.class_to_idx)  # Ensure 'ai' = 0, 'nature' = 1

train_loader = DataLoader(train_ds, batch_size=64, shuffle=True, num_workers=2, pin_memory=True)
val_loader = DataLoader(val_ds, batch_size=64, shuffle=False, num_workers=2, pin_memory=True)

# 2. Model, Loss & Optimizer
model = timm.create_model("efficientnet_b0", pretrained=True, num_classes=2).to(device)
criterion = nn.CrossEntropyLoss()
optimizer = torch.optim.AdamW(model.parameters(), lr=3e-4, weight_decay=1e-4)

EPOCHS = 6
history = {"train_acc": [], "val_acc": [], "train_loss": [], "val_loss": []}
best_acc = 0.0

for epoch in range(EPOCHS):
    # Train
    model.train()
    tr_loss, tr_correct, tr_total = 0.0, 0, 0
    for imgs, labels in train_loader:
        imgs, labels = imgs.to(device), labels.to(device)
        optimizer.zero_grad()
        outputs = model(imgs)
        loss = criterion(outputs, labels)
        loss.backward()
        optimizer.step()

        tr_loss += loss.item() * labels.size(0)
        tr_correct += (outputs.argmax(1) == labels).sum().item()
        tr_total += labels.size(0)

    # Validate
    model.eval()
    va_loss, va_correct, va_total = 0.0, 0, 0
    all_preds, all_labels = [], []
    with torch.no_grad():
        for imgs, labels in val_loader:
            imgs, labels = imgs.to(device), labels.to(device)
            outputs = model(imgs)
            loss = criterion(outputs, labels)

            va_loss += loss.item() * labels.size(0)
            preds = outputs.argmax(1)
            va_correct += (preds == labels).sum().item()
            va_total += labels.size(0)
            all_preds.extend(preds.cpu().numpy())
            all_labels.extend(labels.cpu().numpy())

    train_acc = tr_correct / tr_total
    val_acc = va_correct / va_total
    history["train_acc"].append(train_acc)
    history["val_acc"].append(val_acc)
    history["train_loss"].append(tr_loss / tr_total)
    history["val_loss"].append(va_loss / va_total)

    print(f"Epoch {epoch+1}/{EPOCHS} | Train Acc: {train_acc:.4f} | Val Acc: {val_acc:.4f}")

    if val_acc > best_acc:
        best_acc = val_acc
        best_preds, best_labels = all_preds, all_labels
        torch.save(model.state_dict(), "sd_detector_effnet_b0.pth")

