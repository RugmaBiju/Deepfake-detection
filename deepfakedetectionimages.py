import os
import torch
import torch.nn as nn
import pandas as pd
from torchvision.models import convnext_tiny, ConvNeXt_Tiny_Weights
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score
from tqdm.auto import tqdm

# Configuration
DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
EPOCHS = 3
LEARNING_RATE = 1e-4

MODEL_DIR = "/content/drive/MyDrive/DeepfakeDetection/models"
os.makedirs(MODEL_DIR, exist_ok=True)

CHECKPOINT_PATH = os.path.join(MODEL_DIR, "convnext_tiny_best.pth")

# Load pretrained ConvNeXt-Tiny
weights = ConvNeXt_Tiny_Weights.DEFAULT
model = convnext_tiny(weights=weights)

# Replace final classifier layer
model.classifier[2] = nn.Linear(
    model.classifier[2].in_features, 2
)

model = model.to(DEVICE)

# Training configuration
criterion = nn.CrossEntropyLoss()
optimizer = torch.optim.AdamW(
    model.parameters(),
    lr=LEARNING_RATE,
    weight_decay=0.01
)

scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(
    optimizer, T_max=EPOCHS
)

scaler = torch.amp.GradScaler("cuda", enabled=(DEVICE.type == "cuda"))

def evaluate(model, loader):
    model.eval()
    all_labels = []
    all_predictions = []
    total_loss = 0

    with torch.no_grad():
        for images, labels in loader:
            images = images.to(DEVICE)
            labels = labels.to(DEVICE)

            with torch.amp.autocast(
                device_type=DEVICE.type,
                enabled=(DEVICE.type == "cuda")
            ):
                outputs = model(images)
                loss = criterion(outputs, labels)

            total_loss += loss.item()
            predictions = outputs.argmax(dim=1)

            all_labels.extend(labels.cpu().tolist())
            all_predictions.extend(predictions.cpu().tolist())

    return {
        "loss": total_loss / len(loader),
        "accuracy": accuracy_score(all_labels, all_predictions),
        "precision": precision_score(all_labels, all_predictions, zero_division=0),
        "recall": recall_score(all_labels, all_predictions, zero_division=0),
        "f1": f1_score(all_labels, all_predictions, zero_division=0)
    }

# Training loop
best_f1 = -1
history = []

for epoch in range(EPOCHS):
    model.train()
    running_loss = 0

    progress = tqdm(train_loader, desc=f"Epoch {epoch+1}/{EPOCHS}")

    for images, labels in progress:
        images = images.to(DEVICE, non_blocking=True)
        labels = labels.to(DEVICE, non_blocking=True)

        optimizer.zero_grad(set_to_none=True)

        with torch.amp.autocast(
            device_type=DEVICE.type,
            enabled=(DEVICE.type == "cuda")
        ):
            outputs = model(images)
            loss = criterion(outputs, labels)

        scaler.scale(loss).backward()
        scaler.step(optimizer)
        scaler.update()

        running_loss += loss.item()
        progress.set_postfix(loss=f"{loss.item():.4f}")

    scheduler.step()

    train_loss = running_loss / len(train_loader)
    val_metrics = evaluate(model, val_loader)

    record = {
        "epoch": epoch + 1,
        "train_loss": train_loss,
        **{f"val_{k}": v for k, v in val_metrics.items()}
    }
    history.append(record)

    print(f"\nEpoch {epoch+1}")
    print(f"Training loss: {train_loss:.4f}")
    print(f"Validation accuracy: {val_metrics['accuracy']:.4f}")
    print(f"Validation precision: {val_metrics['precision']:.4f}")
    print(f"Validation recall: {val_metrics['recall']:.4f}")
    print(f"Validation F1: {val_metrics['f1']:.4f}")

    # Save best model based on validation F1
    if val_metrics["f1"] > best_f1:
        best_f1 = val_metrics["f1"]

        torch.save({
            "model_state_dict": model.state_dict(),
            "epoch": epoch + 1,
            "validation_f1": best_f1,
            "class_mapping": {"real": 0, "fake": 1}
        }, CHECKPOINT_PATH)

        print("Best checkpoint saved.")

history_df = pd.DataFrame(history)
history_df.to_csv(
    "/content/drive/MyDrive/DeepfakeDetection/convnext_training_history.csv",
    index=False
)

print("\nCONVNEXT TRAINING COMPLETE")
print("Best validation F1:", round(best_f1, 4))
print("Checkpoint:", CHECKPOINT_PATH)

