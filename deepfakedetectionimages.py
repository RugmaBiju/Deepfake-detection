# Map identical image hashes to their pair IDs
hash_to_pairs = defaultdict(set)

for _, row in manifest.iterrows():
    path = DATASET_DIR / row["class"] / row["filename"]

    with open(path, "rb") as f:
        image_hash = hashlib.sha256(f.read()).hexdigest()

    hash_to_pairs[image_hash].add(row["pair_id"])

# Union-find: merge pair IDs connected by identical images
parent = {pid: pid for pid in manifest["pair_id"].unique()}

def find(x):
    if parent[x] != x:
        parent[x] = find(parent[x])
    return parent[x]

def union(a, b):
    root_a = find(a)
    root_b = find(b)
    if root_a != root_b:
        parent[root_b] = root_a

for pair_ids in hash_to_pairs.values():
    pair_ids = list(pair_ids)
    for pid in pair_ids[1:]:
        union(pair_ids[0], pid)

# Assign each pair to its duplicate-connected group
pairs = pd.DataFrame({
    "pair_id": manifest["pair_id"].unique()
})

pairs["group_id"] = pairs["pair_id"].apply(find)

