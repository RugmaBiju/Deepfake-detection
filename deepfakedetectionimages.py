from tqdm.auto import tqdm

# Feature extraction settings
IMAGE_SIZE = (128, 128)
HOG_CELL_SIZE = (16, 16)
LBP_POINTS = 8
LBP_RADIUS = 1

manifest = pd.read_csv(
    "/content/drive/MyDrive/DeepfakeDetection/dataset_manifest.csv"
)

DATASET_DIR = Path("/content/deepguard")

def extract_features(dataframe):
    hog_features = []
    lbp_features = []
    labels = []

    for _, row in tqdm(dataframe.iterrows(), total=len(dataframe)):
        image_path = DATASET_DIR / row["class"] / row["filename"]

        image = Image.open(image_path).convert("L")
        image = image.resize(IMAGE_SIZE)

        gray = np.asarray(image, dtype=np.float32) / 255.0

        # HOG features
        hog_feature = hog(
            gray,
            orientations=9,
            pixels_per_cell=HOG_CELL_SIZE,
            cells_per_block=(2, 2),
            block_norm="L2-Hys",
            feature_vector=True
        )

        # LBP histogram features
        lbp = local_binary_pattern(
            (gray * 255).astype(np.uint8),
            P=LBP_POINTS,
            R=LBP_RADIUS,
            method="uniform"
        )

        lbp_hist, _ = np.histogram(
            lbp.ravel(),
            bins=np.arange(0, LBP_POINTS + 3),
            range=(0, LBP_POINTS + 2),
            density=True
        )

        hog_features.append(hog_feature)
        lbp_features.append(lbp_hist)
        labels.append(int(row["label"]))

    return (
        np.asarray(hog_features, dtype=np.float32),
        np.asarray(lbp_features, dtype=np.float32),
        np.asarray(labels, dtype=np.int64)
    )


