"""Evaluate deep models at video level"""

def load_trained_model(model_name):
    model = timm.create_model(model_name, pretrained=False, num_classes=2)
    state = torch.load(MODEL_DIR / f'{model_name}_best.pth', map_location=DEVICE, weights_only=True)
    model.load_state_dict(state)
    model.to(DEVICE).eval()
    return model

def metrics_from_video_predictions(y_true, y_prob, model_name):
    y_pred = (np.asarray(y_prob) >= 0.5).astype(int)
    result = {
        'Model': model_name,
        'Accuracy': accuracy_score(y_true, y_pred),
        'Precision': precision_score(y_true, y_pred, zero_division=0),
        'Recall': recall_score(y_true, y_pred, zero_division=0),
        'F1': f1_score(y_true, y_pred, zero_division=0),
        'ROC_AUC': roc_auc_score(y_true, y_prob) if len(set(y_true)) == 2 else np.nan
    }
    print(classification_report(y_true, y_pred, target_names=CLASS_NAMES, zero_division=0))
    print('Confusion matrix:\n', confusion_matrix(y_true, y_pred))
    return result

def evaluate_deep_model(model_name):
    model = load_trained_model(model_name)
    probabilities = defaultdict(list)
    labels_by_video = {}
    with torch.no_grad():
        for images, labels, video_ids in tqdm(test_loader, desc=f'Evaluating {model_name}'):
            images = images.to(DEVICE)
            with torch.autocast(device_type=DEVICE.type, enabled=(DEVICE.type == 'cuda')):
                probs = torch.softmax(model(images), dim=1)[:, 1].cpu().numpy()
            for vid, label, prob in zip(video_ids, labels.numpy(), probs):
                probabilities[vid].append(float(prob))
                labels_by_video[vid] = int(label)
    ordered_ids = list(probabilities.keys())
    y_true = [labels_by_video[v] for v in ordered_ids]
    y_prob = [float(np.mean(probabilities[v])) for v in ordered_ids]
    result = metrics_from_video_predictions(y_true, y_prob, model_name)
    del model
    gc.collect()
    if DEVICE.type == 'cuda': torch.cuda.empty_cache()
    return result

