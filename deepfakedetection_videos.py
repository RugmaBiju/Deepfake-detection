"""Train ConvNeXt-Tiny and ViT-Base (frozen backbone, trained classifier head)"""

from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score, classification_report, confusion_matrix, roc_auc_score
from collections import defaultdict

CLASS_NAMES = ['real', 'fake']

def create_model(model_name):
    model = timm.create_model(model_name, pretrained=True, num_classes=2)
    for param in model.parameters():
        param.requires_grad = False
    for param in model.get_classifier().parameters():
        param.requires_grad = True
    return model.to(DEVICE)

def train_model(model_name, epochs=EPOCHS):
    print(f'\nTraining {model_name}')
    model = create_model(model_name)
    optimizer = optim.AdamW((p for p in model.parameters() if p.requires_grad), lr=1e-3, weight_decay=1e-4)
    criterion = nn.CrossEntropyLoss()
    scaler = torch.amp.GradScaler('cuda', enabled=(DEVICE.type == 'cuda'))
    best_val_loss = float('inf')
    best_path = MODEL_DIR / f'{model_name}_best.pth'

    for epoch in range(epochs):
        model.train()
        train_loss = 0.0
        for images, labels, _ in tqdm(train_loader, desc=f'{model_name} epoch {epoch+1}/{epochs}'):
            images, labels = images.to(DEVICE), labels.to(DEVICE)
            optimizer.zero_grad(set_to_none=True)
            with torch.autocast(device_type=DEVICE.type, enabled=(DEVICE.type == 'cuda')):
                logits = model(images)
                loss = criterion(logits, labels)
            scaler.scale(loss).backward()
            scaler.step(optimizer)
            scaler.update()
            train_loss += loss.item()

        model.eval()
        val_loss = 0.0
        with torch.no_grad():
            for images, labels, _ in val_loader:
                images, labels = images.to(DEVICE), labels.to(DEVICE)
                with torch.autocast(device_type=DEVICE.type, enabled=(DEVICE.type == 'cuda')):
                    logits = model(images)
                    loss = criterion(logits, labels)
                val_loss += loss.item()

        train_loss /= max(1, len(train_loader))
        val_loss /= max(1, len(val_loader))
        print(f'Epoch {epoch+1}: train_loss={train_loss:.4f} | val_loss={val_loss:.4f}')
        if val_loss < best_val_loss:
            best_val_loss = val_loss
            torch.save(model.state_dict(), best_path)

    del model
    gc.collect()
    if DEVICE.type == 'cuda':
        torch.cuda.empty_cache()
    print('Saved:', best_path)

train_model('convnext_tiny')
