"""Extract evenly spaced frames from each video"""

def extract_frames(video_path, video_id, output_dir, num_frames=8, image_size=224):
    cap = cv2.VideoCapture(str(video_path))
    total_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
    if not cap.isOpened() or total_frames < 2:
        cap.release()
        return []

    indices = np.unique(np.linspace(0, total_frames - 1, num_frames, dtype=int))
    video_frame_dir = output_dir / video_id
    video_frame_dir.mkdir(parents=True, exist_ok=True)
    saved = []

    for j, frame_idx in enumerate(indices):
        cap.set(cv2.CAP_PROP_POS_FRAMES, int(frame_idx))
        ok, frame = cap.read()
        if not ok or frame is None:
            continue
        frame = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
        frame = cv2.resize(frame, (image_size, image_size))
        out = video_frame_dir / f'frame_{j:02d}.jpg'
        cv2.imwrite(str(out), cv2.cvtColor(frame, cv2.COLOR_RGB2BGR), [int(cv2.IMWRITE_JPEG_QUALITY), 95])
        saved.append(str(out))

    cap.release()
    return saved

