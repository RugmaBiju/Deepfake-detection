"""Extract a balanced sample"""

def sample_videos_from_archive(zip_path, label, n_samples, output_root):
    label_dir = output_root / label
    label_dir.mkdir(parents=True, exist_ok=True)

    with zipfile.ZipFile(zip_path, 'r') as zf:
        members = [m for m in zf.infolist()
                   if not m.is_dir() and m.filename.lower().endswith(('.mp4', '.mov', '.avi', '.mkv'))]
        if not members:
            raise RuntimeError(f'No video files found inside {zip_path.name}')
        random.shuffle(members)
        chosen = members[:min(n_samples, len(members))]
        records = []
        for i, member in enumerate(tqdm(chosen, desc=f'Extracting {label}')):
            suffix = Path(member.filename).suffix.lower() or '.mp4'
            out_path = label_dir / f'{label}_{i:04d}{suffix}'
            with zf.open(member, 'r') as src, open(out_path, 'wb') as dst:
                shutil.copyfileobj(src, dst)
            records.append({
                'video_id': f'{label}_{i:04d}',
                'label': label,
                'local_path': str(out_path),
                'archive_member': member.filename
            })
    return records

