# ------------------------------------------------------------
# 5. VISUALIZATION 3 — IMPROVEMENT ANALYSIS
# ------------------------------------------------------------

# Differences are reported in percentage points,
# not percentage-relative improvement.

dino_gain = (
    advanced_df.loc["DINOv2"] -
    advanced_df.loc["EfficientNet-B0"]
)

ensemble_gain = (
    advanced_df.loc["EfficientNet-B0 + DINOv2"] -
    advanced_df.loc["DINOv2"]
)

fig3 = make_subplots(
    rows=1,
    cols=2,
    subplot_titles=(
        "<b>DINOv2 vs EfficientNet-B0</b>",
        "<b>Ensemble vs DINOv2</b>"
    ),
    horizontal_spacing=0.16
)

# DINOv2 improvement over EfficientNet
fig3.add_trace(
    go.Bar(
        x=metrics,
        y=dino_gain.values,
        marker_color="#0ea5e9",
        text=[f"+{v:.2f}" for v in dino_gain.values],
        textposition="outside",
        name="DINOv2 gain",
        hovertemplate="%{x}: +%{y:.2f} percentage points<extra></extra>"
    ),
    row=1,
    col=1
)

# Additional improvement from model fusion
fig3.add_trace(
    go.Scatter(
        x=metrics,
        y=ensemble_gain.values,
        mode="markers+text",
        marker=dict(
            color="#8b5cf6",
            size=13,
            line=dict(color="white", width=1)
        ),
        text=[f"+{v:.2f}" for v in ensemble_gain.values],
        textposition="top center",
        name="Ensemble gain",
        hovertemplate="%{x}: +%{y:.2f} percentage points<extra></extra>"
    ),
    row=1,
    col=2
)

fig3.update_layout(
    title=dict(
        text="<b>03 | How Much Does Model Fusion Actually Help?</b><br>"
             "<sup>Difference in percentage points between model configurations</sup>",
        x=0.02
    ),
    template="plotly_white",
    height=460,
    showlegend=False,
    font=dict(family="Arial", size=12),
    margin=dict(l=65, r=40, t=120, b=90),
    paper_bgcolor="#ffffff",
    plot_bgcolor="#ffffff"
)

fig3.update_yaxes(
    title_text="Gain (percentage points)",
    range=[0, 1.7],
    gridcolor="#e2e8f0",
    row=1,
    col=1
)

fig3.update_yaxes(
    title_text="Gain (percentage points)",
    range=[-0.003, 0.032],
    dtick=0.01,
    gridcolor="#e2e8f0",
    row=1,
    col=2
)

fig3.update_xaxes(title_text="Evaluation Metrics")

fig3.show()


