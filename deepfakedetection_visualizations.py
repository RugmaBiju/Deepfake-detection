# 3. VISUALIZATION 1 — MODEL PERFORMANCE HEATMAP
# ------------------------------------------------------------

heatmap_data = baseline_df.values

fig1 = go.Figure(
    data=go.Heatmap(
        z=heatmap_data,
        x=metrics,
        y=baseline_df.index,
        colorscale=[
            [0.00, "#991b1b"],
            [0.40, "#dc6b4c"],
            [0.65, "#facc75"],
            [0.85, "#a7d6a5"],
            [1.00, "#166534"]
        ],
        zmin=0,
        zmax=100,
        text=np.vectorize(lambda x: f"{x:.2f}%")(heatmap_data),
        texttemplate="%{text}",
        textfont=dict(size=13, color="#111827"),
        colorbar=dict(
            title="Score",
            ticksuffix="%",
            thickness=15
        ),
        hovertemplate=(
            "<b>%{y}</b><br>"
            "Metric: %{x}<br>"
            "Score: %{z:.4f}%"
            "<extra></extra>"
        )
    )
)

fig1.update_layout(
    title=dict(
        text="<b>01 | Traditional vs Deep Learning Models</b><br>"
             "<sup>Performance distribution across all five evaluation metrics</sup>",
        x=0.02
    ),
    template="plotly_white",
    height=470,
    font=dict(family="Arial", size=13),
    margin=dict(l=150, r=50, t=100, b=60),
    xaxis=dict(side="bottom", title="Evaluation Metrics"),
    yaxis=dict(title="Model", autorange="reversed"),
    paper_bgcolor="#ffffff",
    plot_bgcolor="#ffffff"
)

fig1.show()


